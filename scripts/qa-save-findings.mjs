// Extracts the consolidated report from the enterprise-qa-hunt workflow output
// and writes it to docs/QA_ENTERPRISE_FINDINGS.md. Read-only on the source.
import { readFileSync, writeFileSync } from 'node:fs'

const SRC = process.argv[2]
const OUT = 'docs/QA_ENTERPRISE_FINDINGS.md'
const raw = JSON.parse(readFileSync(SRC, 'utf-8'))
const r = raw.result
const header = `<!-- Generated by the enterprise-qa-hunt workflow (19 agents: 9 hunt + 9 adversarial verify + synthesis). -->
<!-- Static code audit, ${r.totalConfirmed} verifier-confirmed defects (${r.criticalCount} critical, ${r.highCount} high). Dynamic Playwright pass follows. -->

`
writeFileSync(OUT, header + r.report, 'utf-8')
console.log(`Wrote ${OUT} — ${r.report.length} chars, ${r.totalConfirmed} confirmed defects.`)
